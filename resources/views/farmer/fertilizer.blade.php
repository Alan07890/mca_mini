<script>
document.addEventListener('DOMContentLoaded', function () {
    const $  = (s, r = document) => r.querySelector(s);
    const $$ = (s, r = document) => Array.from(r.querySelectorAll(s));
    const tabs = $$('.gd-dis'), panels = $$('.gd-panel');
    if (!tabs.length) return;

    const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
    const fmtNum = v => new Intl.NumberFormat('en-IN', { maximumFractionDigits: 2 }).format(v);

    $$('.gd-ring .fg').forEach(c => setTimeout(() => { c.style.strokeDashoffset = 100 - (Number(c.dataset.pct) || 0); }, 250));

    /* ---------- select a disease ---------- */
    let currentId = null;
    function select(id, opts) {
        opts = opts || {};
        const tab = tabs.find(t => t.dataset.id === String(id)); if (!tab) return;
        currentId = String(id);
        tabs.forEach(t => { const on = t === tab; t.setAttribute('aria-selected', on); t.tabIndex = on ? 0 : -1; });
        panels.forEach(p => { p.hidden = p.dataset.id !== currentId; });
        const panel = panels.find(p => p.dataset.id === currentId);
        applyChip(panel, ''); highlight(panel); estimate(panel);
        try { history.replaceState(null, '', '#disease-' + currentId); } catch (e) {}
        if (opts.scroll) tab.scrollIntoView({ block: 'nearest', inline: 'center', behavior: 'smooth' });
        if (opts.reveal) panel.scrollIntoView({ block: 'start', behavior: 'smooth' });
        if (opts.focus) tab.focus();
    }
    tabs.forEach(t => t.addEventListener('click', () => select(t.dataset.id, { reveal: window.innerWidth <= 1000 })));
    $('#gd-list').addEventListener('keydown', e => {
        if (!['ArrowDown', 'ArrowUp', 'ArrowRight', 'ArrowLeft', 'Home', 'End'].includes(e.key)) return;
        const vis = tabs.filter(t => !t.hidden); const i = vis.indexOf(document.activeElement); if (i < 0) return;
        e.preventDefault();
        let n = e.key === 'Home' ? 0 : e.key === 'End' ? vis.length - 1 : (e.key === 'ArrowDown' || e.key === 'ArrowRight') ? Math.min(i + 1, vis.length - 1) : Math.max(i - 1, 0);
        select(vis[n].dataset.id, { focus: true, scroll: true });
    });

    /* ---------- type chips inside a panel ---------- */
    function applyChip(panel, cat) {
        if (!panel) return;
        $$('.gd-chip', panel).forEach(c => c.classList.toggle('on', c.dataset.cat === cat));
        let shown = 0;
        $$('.gd-card', panel).forEach(c => { const ok = !cat || c.dataset.cat === cat; c.hidden = !ok; if (ok) shown++; });
        const empty = $('.gd-chipempty', panel); if (empty) empty.hidden = shown !== 0;
    }
    panels.forEach(p => $$('.gd-chip', p).forEach(c => c.addEventListener('click', () => applyChip(p, c.dataset.cat))));

    /* ---------- "also used for" links ---------- */
    document.addEventListener('click', e => {
        const g = e.target.closest('[data-goto]'); if (!g) return;
        select(g.dataset.goto, { scroll: true, reveal: true });
    });

    /* ---------- search + show filter ---------- */
    const search = $('#gd-search'), seg = $$('.gd-seg button'), nomatch = $('#gd-nomatch');
    let show = 'all';
    function filterTabs() {
        const q = (search.value || '').trim().toLowerCase(); let n = 0;
        tabs.forEach(t => {
            const okShow = show === 'all' || (show === 'has' && t.dataset.has === '1') || (show === 'none' && t.dataset.has === '0');
            const ok = okShow && (!q || t.dataset.search.includes(q));
            t.hidden = !ok; if (ok) n++;
        });
        nomatch.hidden = n !== 0;
        const cur = tabs.find(t => t.dataset.id === currentId);
        if (cur && cur.hidden) { const first = tabs.find(t => !t.hidden); if (first) select(first.dataset.id); }
        const panel = panels.find(p => p.dataset.id === currentId); highlight(panel);
    }
    function highlight(panel) {
        if (!panel) return; const q = (search.value || '').trim().toLowerCase();
        $$('.gd-card', panel).forEach(c => c.classList.toggle('is-hit', !!q && c.dataset.name.toLowerCase().includes(q)));
    }
    search.addEventListener('input', filterTabs);
    seg.forEach(b => b.addEventListener('click', () => { show = b.dataset.show; seg.forEach(x => x.classList.toggle('on', x === b)); filterTabs(); }));
    $('#gd-reset').addEventListener('click', () => { search.value = ''; show = 'all'; seg.forEach(x => x.classList.toggle('on', x.dataset.show === 'all')); filterTabs(); });

    /* ---------- estimate for my field ---------- */
    const plants = $('#gd-plants'), acres = $('#gd-acres'), hint = $('#gd-field-p');
    function human(v, u) {
        if (u === 'g' && v >= 1000) return fmtNum(v / 1000) + ' kg';
        if (u === 'ml' && v >= 1000) return fmtNum(v / 1000) + ' L';
        return fmtNum(v) + ' ' + u;
    }
    function calc(card) {
        const d = Number(card.dataset.dosage), r = Number(card.dataset.ref), u = card.dataset.unit, ru = card.dataset.refunit;
        if (!Number.isFinite(d) || d <= 0 || !Number.isFinite(r) || r <= 0 || card.dataset.dosage === '' || card.dataset.ref === '') return null;
        const p = plants.value === '' ? null : Number(plants.value), a = acres.value === '' ? null : Number(acres.value);
        if (ru === 'plant') return p === null ? { need: 'plants' } : { v: d * (p / r), note: 'Based on ' + fmtNum(p) + ' plants at ' + fmtNum(d) + ' ' + u + ' per ' + fmtNum(r) + ' plant.' };
        if (ru === 'acre') return a === null ? { need: 'acres' } : { v: d * (a / r), note: 'Based on ' + fmtNum(a) + ' acre(s) at ' + fmtNum(d) + ' ' + u + ' per ' + fmtNum(r) + ' acre.' };
        if (ru === 'ha') return a === null ? { need: 'acres' } : { v: d * (a * 0.40468564224 / r), note: 'Based on ' + fmtNum(a * 0.40468564224) + ' hectare(s) at ' + fmtNum(d) + ' ' + u + ' per ' + fmtNum(r) + ' hectare.' };
        if (ru === 'L' || ru === 'ml') return { spray: 'Mix ' + fmtNum(d) + ' ' + u + ' in every ' + fmtNum(r) + ' ' + ru + ' of water. The total depends on how much water you use.' };
        return null;
    }
    function estimate(panel) {
        if (!panel) return;
        $$('.gd-card', panel).forEach(card => {
            const box = $('.gd-est', card), c = calc(card);
            if (!c || c.need) { box.hidden = true; return; }
            box.hidden = false;
            if (c.spray) { $('.gd-est-v', box).textContent = 'Spray mix'; $('.gd-est-n', box).textContent = c.spray; }
            else { $('.gd-est-v', box).textContent = human(c.v, card.dataset.unit); $('.gd-est-n', box).textContent = c.note + ' This is an estimate.'; }
        });
    }
    [plants, acres].forEach(i => i.addEventListener('input', () => estimate(panels.find(p => p.dataset.id === currentId))));

    /* ---------- start ---------- */
    const m = (location.hash || '').match(/^#disease-(.+)$/);
    const fromHash = m && tabs.find(t => t.dataset.id === decodeURIComponent(m[1]));
    const first = fromHash || tabs.find(t => t.dataset.has === '1') || tabs[0];
    select(first.dataset.id, { scroll: true });
});
</script>
