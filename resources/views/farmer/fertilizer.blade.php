    /* ---------- Prepare everything once, so the markup below stays simple ---------- */
    $guide = [];
    $usedIn = [];
    $mappings = 0; $organicTotal = 0; $inorganicTotal = 0;

    foreach ($diseaseFertilizers as $categoryId => $items) {
        $name = null; $list = [];
        foreach ($items as $item) {
            $name = $name ?? ($item->diseases_name ?? null);
            if (empty($item->fertilizer_id)) continue;
            $cat = ($item->fertilizer_category ?? '') === 'Organic' ? 'Organic' : 'Inorganic';
            $list[] = [
                'fid'     => $item->fertilizer_id,
                'name'    => $item->fertilizer_name,
                'cat'     => $cat,
                'icon'    => $cat === 'Organic' ? 'fa-leaf' : 'fa-flask',
                'desc'    => $item->description ?? '',
                'dosage'  => is_numeric($item->dosage_amount ?? null) ? (float) $item->dosage_amount : '',
                'unit'    => $item->dosage_unit ?? '',
                'ref'     => is_numeric($item->reference_quantity ?? null) ? (float) $item->reference_quantity : '',
                'refUnit' => $item->reference_unit ?? '',
                'others'  => [],
            ];
        }
        $name = $name ?? 'Disease';
        foreach ($list as $l) { $usedIn[$l['fid']][] = ['id' => $categoryId, 'name' => $name]; }

        $org = 0; $inorg = 0; $names = [];
        foreach ($list as $l) { if ($l['cat'] === 'Organic') $org++; else $inorg++; $names[] = $l['name']; }
        $count = count($list);
        $mappings += $count; $organicTotal += $org; $inorganicTotal += $inorg;

        $guide[] = [
            'id'      => $categoryId,
            'name'    => $name,
            'items'   => $list,
            'count'   => $count,
            'label'   => $count === 1 ? 'fertilizer' : 'fertilizers',
            'sub'     => $count > 0 ? $count.' '.($count === 1 ? 'fertilizer' : 'fertilizers') : 'No mapping yet',
            'has'     => $count > 0 ? '1' : '0',
            'cls'     => $count > 0 ? 'gd-has' : 'gd-none',
            'organic' => $org,
            'inorganic' => $inorg,
            'search'  => strtolower($name.' '.implode(' ', $names)),
        ];
    }

    /* "Also used for" cross references */
    foreach ($guide as $gi => $g) {
        foreach ($g['items'] as $fi => $f) {
            $others = [];
            foreach ($usedIn[$f['fid']] ?? [] as $u) { if ((string) $u['id'] !== (string) $g['id']) $others[] = $u; }
            $guide[$gi]['items'][$fi]['others'] = $others;
        }
    }

    $totalDiseases = count($guide);
    $mappedDiseases = 0; foreach ($guide as $g) { if ($g['count'] > 0) $mappedDiseases++; }
    $coverage = $totalDiseases ? (int) round($mappedDiseases / $totalDiseases * 100) : 0;
    $orgPct = $mappings ? (int) round($organicTotal / $mappings * 100) : 0;

    /* optional field details (only if your controller passes $field) */
    $gf = $field ?? null;
    $gPlants = is_object($gf) ? ($gf->plant_count ?? null) : null;
    $gAcres = null;
    if (is_object($gf) && is_numeric($gf->area ?? null)) {
        $gAcres = (($gf->area_unit ?? 'acre') === 'cent') ? round($gf->area / 100, 2) : (float) $gf->area;
    }

    /* link to the Fertilizer Management page, only if a matching route exists */
    $recordUrl = null;
    if (\Illuminate\Support\Facades\Route::has('farmer.fertilizer.reminder')) { $recordUrl = route('farmer.fertilizer.reminder'); }
    $fieldUrl = \Illuminate\Support\Facades\Route::has('farmer.field') ? route('farmer.field') : null;
@endphp

